--[[
	Single source of truth for the names of every RemoteEvent this game uses.

	Both sides build the remotes themselves rather than relying on instances
	committed into the place file, because the place file is generated by Rojo
	from these scripts - so anything that has to exist at runtime must be created
	at runtime. The server creates them and the client waits, which is why Ensure
	is idempotent on both sides.

	Keeping the names here means a typo shows up as "unknown remote" at startup
	instead of as a silent nil index three files away.
]]

local ReplicatedStorage = game:GetService("ReplicatedStorage")

local Remotes = {}

local NAMES = { "VehicleTouched", "MissionEvent", "Notify", "LaunchMission", "SetMode" }

local function folder()
	local f = ReplicatedStorage:FindFirstChild("CyberRoadster")
	if f == nil then
		f = Instance.new("Folder")
		f.Name = "CyberRoadster"
		if ReplicatedStorage.Parent ~= nil then
			f.Parent = ReplicatedStorage
		end
	end
	return f
end

function Remotes.Ensure()
	local f = folder()
	for _, name in ipairs(NAMES) do
		if f:FindFirstChild(name) == nil then
			local ev = Instance.new("RemoteEvent")
			ev.Name = name
			ev.Parent = f
		end
	end
	return f
end

function Remotes.Get(name)
	local f = folder()
	local ok = f:FindFirstChild(name, true)
	if ok == nil then
		ok = Remotes.Ensure():FindFirstChild(name)
	end
	return ok
end

return Remotes
